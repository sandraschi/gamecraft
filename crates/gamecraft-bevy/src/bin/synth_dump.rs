//! `gamecraft-synth-dump`: write every synthesised effect as a WAV and a spectrogram
//! PNG, plus a loudness table, so the sounds can be reviewed without listening.
//!
//! ```text
//! cargo run -q -p gamecraft-bevy --bin gamecraft-synth-dump [-- DIR] [--check]
//!     DIR      output folder (default docs/sounds)
//!     --check  write nothing; exit 1 if any file on disk differs from a fresh render
//! ```
//!
//! The files are committed on purpose: they are the record of what the games sound
//! like. Nothing in them depends on the date, so a re-run changes bytes only when a
//! formula changes (or when this machine's float maths differs from the one that
//! wrote them).

use gamecraft_bevy::analysis::{levels, spectrogram, spectrogram_png, HOP, WINDOW};
use gamecraft_bevy::synth;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// One effect: file stem, what it is for, and its samples.
struct Effect {
    name: &'static str,
    purpose: &'static str,
    samples: Vec<f32>,
}

fn effects() -> Vec<Effect> {
    vec![
        Effect {
            name: "ambient",
            purpose: "Murmuration bed, loops: low wind and wing rustle under two soft pad tones (110 and 165 Hz)",
            samples: synth::ambient(),
        },
        Effect {
            name: "screech",
            purpose: "Murmuration: a hawk takes a starling; a sweep falling from about 3.4 kHz to 2.2 kHz with a flutter",
            samples: synth::screech(),
        },
        Effect {
            name: "flare",
            purpose: "Murmuration: the flare; a noise whoosh that brightens, over a falling sparkle",
            samples: synth::flare(),
        },
        Effect {
            name: "win_chime",
            purpose: "Both games: win; four rising notes C5 E5 G5 C6 with a soft octave overtone",
            samples: synth::win_chime(),
        },
        Effect {
            name: "loss_tone",
            purpose: "Murmuration: loss; a low falling tone (196 to 147 Hz)",
            samples: synth::loss_tone(),
        },
        Effect {
            name: "blip",
            purpose: "Maze: one step; 70 ms rising blip",
            samples: synth::blip(),
        },
        Effect {
            name: "bump",
            purpose: "Maze: a wall; 110 ms low thump",
            samples: synth::bump(),
        },
    ]
}

/// Everything to write, as (relative file name, bytes).
fn render() -> Vec<(String, Vec<u8>)> {
    let mut files = Vec::new();
    let mut report = String::new();
    report.push_str("# Sounds\n\n");
    report.push_str(
        "Generated by `cargo run -q -p gamecraft-bevy --bin gamecraft-synth-dump`; do not edit by hand.\n",
    );
    report.push_str(
        "Every effect is computed in `crates/gamecraft-bevy/src/synth.rs`, so these files are the\n\
         complete record of what the Bevy games sound like.\n\n",
    );
    let _ = writeln!(
        report,
        "Spectrogram key: time runs left to right, 0 Hz is the bottom edge and {} Hz the top; white ticks on the left mark every 1 kHz (long every 5 kHz), ticks under the image every 0.5 s (long every 1 s). Brighter is louder, on a {:.0} dB range per image. FFT window {WINDOW} samples, hop {HOP}.\n",
        synth::SAMPLE_RATE / 2,
        -gamecraft_bevy::analysis::FLOOR_DB
    );
    report
        .push_str("| Effect | Length | Peak | RMS | Centroid | Use |\n|---|---|---|---|---|---|\n");
    let mut sections = String::new();
    for effect in effects() {
        let lv = levels(&effect.samples);
        let spec = spectrogram(&effect.samples);
        let _ = writeln!(
            report,
            "| [{n}]({n}.wav) | {:.2} s | {:.1} dBFS | {:.1} dBFS | {:.0} Hz | {} |",
            lv.seconds,
            lv.peak_db,
            lv.rms_db,
            spec.centroid_hz,
            effect.purpose,
            n = effect.name
        );
        let _ = writeln!(
            sections,
            "## {n}\n\n{}\n\n![{n} spectrogram]({n}.png)\n",
            effect.purpose,
            n = effect.name
        );
        files.push((
            format!("{}.wav", effect.name),
            synth::wav_bytes(&effect.samples),
        ));
        files.push((format!("{}.png", effect.name), spectrogram_png(&spec)));
    }
    report.push('\n');
    report.push_str(&sections);
    files.push(("REPORT.md".to_string(), report.into_bytes()));
    files
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let check = args.iter().any(|a| a == "--check");
    let dir = args
        .iter()
        .find(|a| !a.starts_with("--"))
        .map_or_else(|| PathBuf::from("docs/sounds"), PathBuf::from);
    let files = render();
    if check {
        let stale: Vec<&str> = files
            .iter()
            .filter(|(name, bytes)| std::fs::read(dir.join(name)).ok().as_ref() != Some(bytes))
            .map(|(name, _)| name.as_str())
            .collect();
        if stale.is_empty() {
            println!("sounds: {} files match a fresh render", files.len());
        } else {
            eprintln!("sounds: out of date: {}", stale.join(", "));
            std::process::exit(1);
        }
        return;
    }
    if let Err(err) = std::fs::create_dir_all(&dir) {
        eprintln!("cannot create {}: {err}", dir.display());
        std::process::exit(1);
    }
    for (name, bytes) in &files {
        let path: &Path = &dir.join(name);
        if let Err(err) = std::fs::write(path, bytes) {
            eprintln!("cannot write {}: {err}", path.display());
            std::process::exit(1);
        }
    }
    println!("sounds: wrote {} files to {}", files.len(), dir.display());
}
